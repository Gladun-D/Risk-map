def seed_demo(db: RiskDB, today: date | None = None, rng_seed: int = 42) -> None:
    today = today or date.today()
    rnd = random.Random(rng_seed)
    first_week = week_start(today) - timedelta(weeks=WEEKS - 1)
    for idx, (title, desc, cat, owner, strategy, plan, trigger, start, scenario) in enumerate(DEMO, start=1):
        start_week = first_week + timedelta(weeks=rnd.randint(7, 10)) if scenario in ("new", "unassessed") else first_week
        created_on = start_week + timedelta(days=rnd.randint(0, 2))
        due = today + timedelta(days=rnd.choice([-9, -3, 4, 6, 12, 20, 35, 50])) if plan else None
        target = (max(1, start[0] - 2), max(1, start[1] - 1)) if start else (None, None)
        rid = db.create_risk({
            "code": f"R-{idx:03d}", "title": title, "description": desc, "category": cat, "owner": owner,
            "status": "Выявлен", "strategy": strategy, "response_plan": plan, "due_date": due, "trigger": trigger,
            "target_p": target[0], "target_i": target[1], "source": "demo", "created_on": created_on,
        }, actor="демо-наполнение")
        if start is None:
            continue
        p, i = start
        weeks = (today - created_on).days // 7 + 1
        close_after = rnd.randint(6, 9) if scenario == "closed" else None
        for w in range(weeks):
            on = created_on + timedelta(days=7 * w + rnd.randint(0, 3))
            if on > today:
                break
            closing = close_after is not None and w == close_after
            if w > 0:
                if rnd.random() > 0.45 and not closing:  # переоценивают не каждую неделю
                    continue
                p, i = _step(p, i, "fall" if closing else scenario, rnd)
            db.add_assessment(rid, p, i, on, comment="Плановый пересмотр" if w else "Первичная оценка",
                              author=owner or "Риск-менеджер", source="demo", log=False)
            if closing:
                closed = on + timedelta(days=1)
                db.update_risk(rid, {"status": "Закрыт"}, actor="демо-наполнение")
                db._exec("UPDATE risk SET closed_on=? WHERE id=?", (closed.isoformat(), rid))
                break
        else:
            status = {"grow": "В обработке", "fall": "На мониторинге", "flat": "В обработке", "new": "Оценён"}.get(scenario, "Оценён")
            db.update_risk(rid, {"status": status}, actor="демо-наполнение")
    db.set_setting("demo", True)


def _step(p: int, i: int, scenario: str, rnd: random.Random) -> tuple[int, int]:
    bias = {"grow": 0.65, "fall": 0.25}.get(scenario, 0.5)
    delta = 1 if rnd.random() < bias else -1
    if rnd.random() < 0.7:
        p = min(5, max(1, p + delta))
    else:
        i = min(5, max(1, i + delta))
    return p, i
